-- 05_grants.sql : OPTIONAL. Skip when running everything as SYSADMIN; it needs the PI_BI_* roles to exist.
-- Access model. Run as PI_BI_OWNER after the procedure and tables exist.
--
--   Function API  (PI_BI_API)   -> may only CALL EXECUTE_QUERY. No table access at all.
--   Maintainers   (PI_BI_ADMIN) -> edit the metadata tables, read caches and logs.
--   EXECUTE_QUERY runs as PI_BI_OWNER, which reads PI.CORE and reads/writes PI.BI_ENGINE.

USE ROLE PI_BI_OWNER;
USE DATABASE PI;

-- Function API
GRANT USAGE   ON SCHEMA PI.BI_ENGINE TO ROLE PI_BI_API;
GRANT USAGE   ON PROCEDURE PI.BI_ENGINE.EXECUTE_QUERY(VARIANT, VARCHAR, VARCHAR, BOOLEAN, BOOLEAN) TO ROLE PI_BI_API;

-- Metadata maintainers
GRANT USAGE ON SCHEMA PI.BI_ENGINE TO ROLE PI_BI_ADMIN;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE PI.BI_ENGINE.MEASURE_DETAILS                TO ROLE PI_BI_ADMIN;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE PI.BI_ENGINE.MEASURE_FILTER_DETAILS         TO ROLE PI_BI_ADMIN;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE PI.BI_ENGINE.ATTRIBUTE_DETAILS              TO ROLE PI_BI_ADMIN;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE PI.BI_ENGINE.RELATIONSHIP_METADATA_DETAILS  TO ROLE PI_BI_ADMIN;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE PI.BI_ENGINE.CROSSFACT_JOIN_KEY_POLICY      TO ROLE PI_BI_ADMIN;
GRANT SELECT, TRUNCATE               ON TABLE PI.BI_ENGINE.EXECUTE_QUERY_CACHE            TO ROLE PI_BI_ADMIN;
GRANT SELECT, TRUNCATE               ON TABLE PI.BI_ENGINE.CUSTOM_QUERY_CACHE             TO ROLE PI_BI_ADMIN;
GRANT SELECT ON TABLE PI.BI_ENGINE.EXECUTE_QUERY_LOG        TO ROLE PI_BI_ADMIN;
GRANT SELECT ON TABLE PI.BI_ENGINE.EXECUTE_QUERY_ERROR_LOG  TO ROLE PI_BI_ADMIN;
